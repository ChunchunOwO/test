import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDirectory, '..');
const aboutDirectory = path.join(projectRoot, 'src', 'renderer', 'pages', 'settings', 'about');
const configPath = path.join(aboutDirectory, 'contributors.config.json');
const outputPath = path.join(aboutDirectory, 'contributors.github.generated.ts');

const config = JSON.parse(await readFile(configPath, 'utf8'));
const repository = String(config.githubRepository ?? '').trim();
if (!/^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/.test(repository)) {
  throw new Error(`Invalid githubRepository in ${configPath}`);
}

const blacklist = new Set(
  (Array.isArray(config.blacklist) ? config.blacklist : [])
    .map((value) => String(value).trim().toLocaleLowerCase('en-US'))
    .filter(Boolean),
);
const headers = {
  Accept: 'application/vnd.github+json',
  'User-Agent': 'ECHO-contributor-sync',
  'X-GitHub-Api-Version': '2022-11-28',
};
if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;

const contributors = [];
let nextUrl = `https://api.github.com/repos/${repository}/contributors?per_page=100&anon=1`;

while (nextUrl) {
  const response = await fetch(nextUrl, { headers });
  if (!response.ok) {
    const responseBody = await response.text();
    throw new Error(`GitHub contributor sync failed (${response.status}): ${responseBody.slice(0, 400)}`);
  }

  const page = await response.json();
  if (!Array.isArray(page)) throw new Error('GitHub contributors response was not an array');
  contributors.push(...page);

  const nextLink = (response.headers.get('link') ?? '')
    .split(',')
    .map((part) => part.trim())
    .find((part) => part.endsWith('rel="next"'));
  nextUrl = nextLink?.match(/^<([^>]+)>/)?.[1] ?? '';
}

const seen = new Set();
const contributorIds = [];
let skippedAnonymous = 0;
for (const contributor of contributors) {
  const id = typeof contributor?.login === 'string' ? contributor.login.trim() : '';
  if (!id) {
    skippedAnonymous += 1;
    continue;
  }
  if (!/^[A-Za-z0-9](?:[A-Za-z0-9-]{0,38})$/.test(id)) {
    throw new Error(`GitHub returned an invalid contributor login: ${JSON.stringify(id)}`);
  }

  const normalizedId = id.toLocaleLowerCase('en-US');
  if (blacklist.has(normalizedId) || seen.has(normalizedId)) continue;
  seen.add(normalizedId);
  contributorIds.push(id);
}

const generatedSource = `/**
 * Generated by \`npm run sync:contributors\` from GitHub's contributors API.
 * Do not edit this file directly; use contributors.config.json for additions
 * and exclusions that are not represented by repository commits.
 */
export const githubContributorIds = [
${contributorIds.map((id) => `  '${id}',`).join('\n')}
] as const;
`;

await writeFile(outputPath, generatedSource, 'utf8');
console.log(`Synced ${contributorIds.length} GitHub contributors from ${repository}.`);
if (blacklist.size > 0) console.log(`Applied ${blacklist.size} contributor blacklist entr${blacklist.size === 1 ? 'y' : 'ies'}.`);
if (skippedAnonymous > 0) console.log(`Skipped ${skippedAnonymous} anonymous commit author${skippedAnonymous === 1 ? '' : 's'} without GitHub IDs.`);
